def _resolve(dotted):
    module, name = dotted.split(".")
    return getattr(importlib.import_module(f"latticelife.experiments.{module}"), name)


@pytest.mark.parametrize("name", sorted(SIGNATURES))
def test_signature_is_stable(name):
    params = list(inspect.signature(_resolve(name)).parameters)
    assert params == SIGNATURES[name], f"{name} changed: note it in docs/CHANGELOG.md"


@pytest.mark.parametrize("name", sorted(FIELDS))
def test_fields_are_stable(name):
    fields = [f.name for f in dataclasses.fields(_resolve(name))]
    assert fields == FIELDS[name], f"{name} changed: note it in docs/CHANGELOG.md"
